"""Writes `crates/automation/tests/lazy_loading/cases.rs`: the cases of
`tools/probes/web-lazy-loading.json` with Chromium's values.

Run Chromium three times and check that the outputs are equal (docs/testing.md),
then pass one output:

    uv run --project tools swbtools probe --json tools/probes/web-lazy-loading.json > chromium.json
    uv run --project tools swbtools lazy-cases chromium.json
    just fmt
"""

import json
from pathlib import Path
from typing import Any

from swbtools import paths

PROBE_FILE = Path("tools/probes/web-lazy-loading.json")
CASES_FILE = Path("crates/automation/tests/lazy_loading/cases.rs")
DEFAULT_VIEWPORT = (800, 600)


def raw(text: str) -> str:
    """Returns `text` as a Rust raw string literal."""
    for n in range(10):
        fence = "#" * n
        if f'"{fence}' not in text:
            return f'r{fence}"{text}"{fence}'
    raise ValueError("no raw string fence is free")


def render(probe: dict[str, Any], chromium: dict[str, Any]) -> str:
    """Returns the Rust source of the cases: the probe file `probe` with the
    values in the `probe --json` output `chromium`. Raises `KeyError` for a
    case that Chromium did not run."""
    results = {c["name"]: c["results"] for c in chromium["cases"]}
    lines = [
        "// The cases of tools/probes/web-lazy-loading.json with the values of Chromium 148.0.",
        "// Generated by `swbtools lazy-cases` from `swbtools probe --json` (three runs, all",
        '// equal; then `just fmt`; see docs/testing.md, "Lazy loading tests"); do not edit.',
        "",
        "use crate::{Case, Res};",
        "",
        "pub(crate) const CASES: &[Case] = &[",
    ]
    for case in probe["cases"]:
        viewport = case.get("viewport") or probe.get("viewport") or DEFAULT_VIEWPORT
        javascript = case.get("javascript", probe.get("javascript", False))
        lines.append("    Case {")
        lines.append(f'        name: "{case["name"]}",')
        lines.append(f"        html: {raw(case['html'])},")
        lines.append(f"        viewport: ({float(viewport[0])!r}, {float(viewport[1])!r}),")
        lines.append(f"        javascript: {'true' if javascript else 'false'},")
        lines.append(f"        steps: {raw(json.dumps(case.get('steps', [])))},")
        lines.append("        resources: &[")
        for name, res in case.get("resources", {}).items():
            content_type = res.get("content_type")
            wrapped = f"Some({raw(content_type)})" if content_type else "None"
            lines.append("            Res {")
            lines.append(f"                path: {raw(name)},")
            lines.append(f"                text: {raw(res['text'])},")
            lines.append(f"                delay_ms: {res.get('delay_ms', 0)},")
            lines.append(f"                content_type: {wrapped},")
            lines.append("            },")
        lines.append("        ],")
        lines.append("        queries: &[")
        for measure, result in zip(case["measure"], results[case["name"]], strict=True):
            value = json.dumps(result["value"], separators=(",", ":"))
            lines.append(f"            ({raw(measure['js'])}, {raw(value)}),")
        lines.append("        ],")
        lines.append("    },")
    lines.append("];")
    return "\n".join(lines) + "\n"


def write_lazy_cases(chromium_json: Path) -> int:
    """Writes the cases file from the `probe --json` output in `chromium_json`."""
    root = paths.repo_root()
    probe = json.loads((root / PROBE_FILE).read_text())
    chromium = json.loads(chromium_json.read_text())
    (root / CASES_FILE).write_text(render(probe, chromium))
    print(f"wrote {CASES_FILE}")
    return 0
