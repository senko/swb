"""Writes the Rust cases of a probe file for the runtime tests of `crates/web/tests`:
each case with its page, its queries and Chromium's values (`Case` in
`tests/common/mod.rs`).

Run Chromium three times and check that the outputs are equal (docs/testing.md),
then pass the probe file, one output and the Rust file to write:

    uv run --project tools swbtools probe --json tools/probes/web-node-iterator.json > chromium.json
    uv run --project tools swbtools web-cases tools/probes/web-node-iterator.json chromium.json \\
        crates/web/tests/node_iterator/cases.rs
    just fmt
"""

import json
import logging
from pathlib import Path
from typing import Any

from swbtools import paths

log = logging.getLogger(__name__)


def raw(text: str) -> str:
    """Returns `text` as a Rust raw string literal."""
    for n in range(10):
        fence = "#" * n
        if f'"{fence}' not in text:
            return f'r{fence}"{text}"{fence}'
    raise ValueError("no raw string fence is free")


def render(probe: dict[str, Any], chromium: dict[str, Any], probe_file: str) -> str:
    """Returns the Rust source of the cases: the probe file `probe` (named
    `probe_file` in the header) with the values in the `probe --json` output
    `chromium`. Raises `KeyError` for a case that Chromium did not run and
    `ValueError` for a query without a value."""
    results = {c["name"]: c["results"] for c in chromium["cases"]}
    lines = [
        f"// The cases of {probe_file} with the values of Chromium 148.",
        "// Generated by `swbtools web-cases` from `swbtools probe --json` (three runs, all",
        "// equal; then `just fmt`; see docs/testing.md); do not edit.",
        "",
        "use crate::common::Case;",
        "",
        "pub(crate) const CASES: &[Case] = &[",
    ]
    for case in probe["cases"]:
        lines.append("    Case {")
        lines.append(f"        name: {raw(case['name'])},")
        lines.append(f"        html: {raw(case['html'])},")
        lines.append("        queries: &[")
        for measure, result in zip(case["measure"], results[case["name"]], strict=True):
            if "value" not in result:
                raise ValueError(f"{case['name']}: {measure['js'][:60]}: {result}")
            value = json.dumps(result["value"])
            lines.append(f"            ({raw(measure['js'])}, {raw(value)}),")
        lines.append("        ],")
        lines.append("    },")
    lines.append("];")
    return "\n".join(lines) + "\n"


def write_web_cases(probe_file: Path, chromium_json: Path, rust_file: Path) -> int:
    """Writes `rust_file` (relative to the repository root) from the probe file
    and the `probe --json` output in `chromium_json`."""
    root = paths.repo_root()
    for name, path in (("probe file", root / probe_file), ("Chromium output", chromium_json)):
        if not path.is_file():
            log.error("no such %s: %s", name, path)
            return 2
    probe = json.loads((root / probe_file).read_text())
    chromium = json.loads(chromium_json.read_text())
    (root / rust_file).write_text(render(probe, chromium, probe_file.as_posix()))
    print(f"wrote {rust_file}")
    return 0
