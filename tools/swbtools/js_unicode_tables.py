"""`swbtools js-unicode-tables`: Unicode tables for the JavaScript engine.

Writes five files in `crates/js-text/src/unicode/` from the Unicode
Character Database (`ucd.py` downloads the files into `out/ucd/`):
`case_tables.rs` (`js_case_tables.py`), `norm_tables.rs`
(`js_norm_tables.py`), `property_names.rs` (`js_property_names.py`),
`property_data.rs` (`js_property_sets.py`) and `tables.rs`:

- `ID_START`, `ID_CONTINUE`: the properties ID_Start and ID_Continue
  (ECMA-262 §12.7, UnicodeIDStart and UnicodeIDContinue).
- `SPACE_SEPARATORS`: General_Category Zs, the USP of ECMA-262 §12.2.

The tables are sorted, disjoint ranges of code points.
"""

from pathlib import Path

from swbtools import paths
from swbtools.js_case_tables import generate_case_tables
from swbtools.js_norm_tables import generate_norm_tables
from swbtools.js_property_names import generate_property_names, value_aliases
from swbtools.js_property_sets import FILES as SET_FILES
from swbtools.js_property_sets import generate_property_data
from swbtools.ucd import has_property, range_table, ranges, read_property, ucd_file

VERSION = "17.0.0"
"""The Unicode version of the tables."""

FILES = {
    "DerivedCoreProperties": "ucd/DerivedCoreProperties.txt",
    "DerivedGeneralCategory": "ucd/extracted/DerivedGeneralCategory.txt",
}


def generate_tables(core: Path, category: Path) -> str:
    """Returns the Rust source of `tables.rs` from the two UCD files."""
    lines = [
        "//! Unicode data for the JavaScript lexer. Generated by",
        "//! `swbtools js-unicode-tables` (`tools/swbtools/js_unicode_tables.py`) from",
        f"//! the Unicode Character Database {VERSION}",
        f"//! (<https://www.unicode.org/Public/{VERSION}/ucd/>). Do not edit.",
        "",
    ]
    lines += range_table(
        "ID_START",
        "`ID_Start`: `UnicodeIDStart` of ECMA-262 §12.7.",
        ranges(has_property(core, "ID_Start")),
    )
    lines += range_table(
        "ID_CONTINUE",
        "`ID_Continue`: `UnicodeIDContinue` of ECMA-262 §12.7.",
        ranges(has_property(core, "ID_Continue")),
    )
    lines += range_table(
        "SPACE_SEPARATORS",
        "`General_Category` Zs: USP of ECMA-262 §12.2.",
        ranges([gc == "Zs" for gc in read_property(category, "Cn")]),
    )
    return "\n".join(lines).rstrip("\n") + "\n"


def tables_path() -> Path:
    """Returns `crates/js-text/src/unicode/tables.rs`."""
    return paths.repo_root() / "crates" / "js-text" / "src" / "unicode" / "tables.rs"


def write_tables() -> int:
    """Writes the five table files and downloads `NormalizationTest.txt`
    for the full normalization test. Returns the exit code."""
    core = ucd_file(FILES["DerivedCoreProperties"], VERSION)
    outputs = {
        "tables.rs": generate_tables(core, ucd_file(FILES["DerivedGeneralCategory"], VERSION)),
        "case_tables.rs": generate_case_tables(
            ucd_file("ucd/UnicodeData.txt", VERSION),
            ucd_file("ucd/SpecialCasing.txt", VERSION),
            ucd_file("ucd/CaseFolding.txt", VERSION),
            core,
            VERSION,
        ),
        "norm_tables.rs": generate_norm_tables(
            ucd_file("ucd/UnicodeData.txt", VERSION),
            ucd_file("ucd/DerivedNormalizationProps.txt", VERSION),
            VERSION,
        ),
        "property_names.rs": generate_property_names(
            ucd_file("ucd/PropertyAliases.txt", VERSION),
            ucd_file("ucd/PropertyValueAliases.txt", VERSION),
            VERSION,
        ),
    }
    values = ucd_file("ucd/PropertyValueAliases.txt", VERSION)
    outputs["property_data.rs"] = generate_property_data(
        {name: ucd_file(path, VERSION) for name, path in SET_FILES.items()},
        [row[0] for row in value_aliases(values, "gc")],
        value_aliases(values, "sc"),
        VERSION,
    )
    directory = tables_path().parent
    directory.mkdir(parents=True, exist_ok=True)
    for name, source in outputs.items():
        path = directory / name
        path.write_text(source, encoding="utf-8")
        print(f"wrote {path.relative_to(paths.repo_root())}")
    # Not a table: the input of the ignored full-file test of
    # `crates/js-text/tests/normalization.rs`.
    test_file = ucd_file("ucd/NormalizationTest.txt", VERSION)
    print(f"have {test_file.relative_to(paths.repo_root())}")
    return 0
