"""Writes `crates/engine/tests/cssom_sheets/cases.rs`: the cases of
`tools/probes/web-cssom-sheets.json` with Chromium's values.

Run Chromium three times and check that the outputs are equal (docs/testing.md),
then pass one output:

    uv run --project tools swbtools probe --json tools/probes/web-cssom-sheets.json > chromium.json
    uv run --project tools swbtools cssom-cases chromium.json
    just fmt
"""

import json
from pathlib import Path
from typing import Any

from swbtools import paths
from swbtools.rust_cases import raw

PROBE_FILE = Path("tools/probes/web-cssom-sheets.json")
CASES_FILE = Path("crates/engine/tests/cssom_sheets/cases.rs")


def render(probe: dict[str, Any], chromium: dict[str, Any]) -> str:
    """Returns the Rust source of the cases: the probe file `probe` with the
    values in the `probe --json` output `chromium`. Cases that share a page
    share one constant. Raises `KeyError` for a case that Chromium did not
    run."""
    results = {c["name"]: c["results"] for c in chromium["cases"]}
    pages: list[str] = []
    out = [
        "// The cases of tools/probes/web-cssom-sheets.json with the values of Chromium 148.",
        "// Generated by `swbtools cssom-cases` from `swbtools probe --json` (three runs, all",
        '// equal; then `just fmt`; see docs/testing.md, "CSSOM style sheet tests"); do not edit.',
        "// Where swb departs on purpose, the test overrides the value (`SWB_VALUES`).",
        "",
        "use crate::Case;",
        "",
    ]
    body = []
    for case in probe["cases"]:
        if case["html"] not in pages:
            pages.append(case["html"])
        page = pages.index(case["html"]) + 1
        body.append("    Case {")
        body.append(f"        name: {raw(case['name'])},")
        body.append(f"        html: PAGE_{page},")
        body.append("        resources: &[")
        for path, res in case.get("resources", {}).items():
            content_type = res.get("content_type", "text/plain")
            body.append(f"            ({raw(path)}, {raw(content_type)}, {raw(res['text'])}),")
        body.append("        ],")
        body.append("        queries: &[")
        for query, result in zip(case["measure"], results[case["name"]], strict=True):
            value = json.dumps(result["value"], ensure_ascii=False)
            body.append(f"            ({raw(query['js'])}, {raw(value)}),")
        body.append("        ],")
        body.append("    },")
    for number, html in enumerate(pages, 1):
        out.append(f"/// Page {number} of the cases.")
        out.append(f"pub(crate) const PAGE_{number}: &str = {raw(html)};")
        out.append("")
    out.append("pub(crate) const CASES: &[Case] = &[")
    out.extend(body)
    out.append("];")
    return "\n".join(out) + "\n"


def write_cssom_cases(chromium_json: Path) -> int:
    """Writes the cases file from the `probe --json` output in `chromium_json`."""
    root = paths.repo_root()
    probe = json.loads((root / PROBE_FILE).read_text(encoding="utf-8"))
    chromium = json.loads(chromium_json.read_text(encoding="utf-8"))
    (root / CASES_FILE).write_text(render(probe, chromium), encoding="utf-8")
    print(f"wrote {CASES_FILE}")
    return 0
