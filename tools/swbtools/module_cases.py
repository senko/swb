"""Writes `crates/engine/tests/probe_net/modules.rs`: the cases of
`tools/probes/web-module-scripts.json` with Chromium's values.

Run Chromium three times and check that the outputs are equal (docs/testing.md),
then pass one output:

    uv run --project tools swbtools probe --json \\
        tools/probes/web-module-scripts.json > chromium.json
    uv run --project tools swbtools module-cases chromium.json
    just fmt
"""

import json
from pathlib import Path
from typing import Any

from swbtools import paths

PROBE_FILE = Path("tools/probes/web-module-scripts.json")
CASES_FILE = Path("crates/engine/tests/probe_net/modules.rs")


def raw(text: str) -> str:
    """Returns `text` as a Rust raw string literal."""
    for n in range(10):
        fence = "#" * n
        if f'"{fence}' not in text:
            return f'r{fence}"{text}"{fence}'
    raise ValueError("no raw string fence is free")


def render(probe: dict[str, Any], chromium: dict[str, Any]) -> str:
    """Returns the Rust source of the cases: the probe file `probe` with the
    values in the `probe --json` output `chromium`. Raises `KeyError` for a
    case that Chromium did not run."""
    results = {c["name"]: c["results"] for c in chromium["cases"]}
    out = [
        "// The cases of tools/probes/web-module-scripts.json with the values of Chromium 148.0.",
        "// Generated by `swbtools module-cases` from `swbtools probe --json` (three runs, all",
        '// equal; then `just fmt`; see docs/testing.md, "Module script tests"); do not edit.',
        "",
        "use crate::{Case, Options, Res};",
        "",
        "pub(crate) const CASES: &[Case] = &[",
    ]
    for case in probe["cases"]:
        out.append("    Case {")
        out.append(f"        name: {raw(case['name'])},")
        out.append(f"        html: {raw(case['html'])},")
        out.append("        resources: &[")
        for path, res in case.get("resources", {}).items():
            content_type = res.get("content_type")
            wrapped = f"Some({raw(content_type)})" if content_type else "None"
            headers = ", ".join(f"({raw(k)}, {raw(v)})" for k, v in res.get("headers", {}).items())
            out.append("            Res {")
            out.append(f"                path: {raw(path)},")
            out.append(f"                text: {raw(res['text'])},")
            out.append(f"                status: {res.get('status', 200)},")
            out.append(f"                delay_ms: {res.get('delay_ms', 0)},")
            out.append(f"                content_type: {wrapped},")
            out.append(f"                headers: &[{headers}],")
            out.append("                options: Options::None,")
            out.append("            },")
        out.append("        ],")
        out.append("        queries: &[")
        for query, result in zip(case["measure"], results[case["name"]], strict=True):
            value = json.dumps(result["value"], separators=(",", ":"), ensure_ascii=False)
            out.append(f"            ({raw(query['js'])}, {raw(value)}),")
        out.append("        ],")
        out.append("    },")
    out.append("];")
    return "\n".join(out) + "\n"


def write_module_cases(chromium_json: Path) -> int:
    """Writes the cases file from the `probe --json` output in `chromium_json`."""
    root = paths.repo_root()
    probe = json.loads((root / PROBE_FILE).read_text(encoding="utf-8"))
    chromium = json.loads(chromium_json.read_text(encoding="utf-8"))
    (root / CASES_FILE).write_text(render(probe, chromium), encoding="utf-8")
    print(f"wrote {CASES_FILE}")
    return 0
