"""Writes the Rust cases of the module probe files with Chromium's values:
`crates/engine/tests/probe_net/modules.rs` from
`tools/probes/web-module-scripts.json` (`module-cases`) and
`crates/engine/tests/probe_net/module_graph.rs` from
`tools/probes/web-module-graph.json` (`module-graph-cases`; without the
cases of ADR 0034 sub-feature 3b-2, `GRAPH_LATER`).

Run Chromium three times and check that the outputs are equal (docs/testing.md),
then pass one output:

    uv run --project tools swbtools probe --json \\
        tools/probes/web-module-scripts.json > chromium.json
    uv run --project tools swbtools module-cases chromium.json
    just fmt
"""

import json
from collections.abc import Callable
from pathlib import Path
from typing import Any

from swbtools import paths
from swbtools.rust_cases import raw

PROBE_FILE = Path("tools/probes/web-module-scripts.json")
CASES_FILE = Path("crates/engine/tests/probe_net/modules.rs")
GRAPH_PROBE_FILE = Path("tools/probes/web-module-graph.json")
GRAPH_CASES_FILE = Path("crates/engine/tests/probe_net/module_graph.rs")


def graph_later(name: str) -> bool:
    """True for a case of the module graph probe that ADR 0034 sub-feature
    3b-2 runs (import maps, `modulepreload`, the base URLs of classic
    scripts for `import()`)."""
    return (
        name.startswith("importmap-")
        or name.startswith("modulepreload")
        or name == "import-call-base"
    )


def render(
    probe: dict[str, Any],
    chromium: dict[str, Any],
    probe_file: Path = PROBE_FILE,
    skip: Callable[[str], bool] = lambda _: False,
) -> str:
    """Returns the Rust source of the cases: the probe file `probe` with the
    values in the `probe --json` output `chromium`, without the cases that
    `skip` names. Raises `KeyError` for a case that Chromium did not run."""
    results = {c["name"]: c["results"] for c in chromium["cases"]}
    command = "module-cases" if probe_file == PROBE_FILE else "module-graph-cases"
    out = [
        f"// The cases of {probe_file.as_posix()} with the values of Chromium 148.0.",
        f"// Generated by `swbtools {command}` from `swbtools probe --json` (three runs, all",
        '// equal; then `just fmt`; see docs/testing.md, "Module script tests"); do not edit.',
        "",
        "use crate::{Case, Options, Res};",
        "",
        "pub(crate) const CASES: &[Case] = &[",
    ]
    for case in probe["cases"]:
        if skip(case["name"]):
            continue
        out.append("    Case {")
        out.append(f"        name: {raw(case['name'])},")
        out.append(f"        html: {raw(case['html'])},")
        out.append("        resources: &[")
        for path, res in case.get("resources", {}).items():
            content_type = res.get("content_type")
            wrapped = f"Some({raw(content_type)})" if content_type else "None"
            headers = ", ".join(f"({raw(k)}, {raw(v)})" for k, v in res.get("headers", {}).items())
            out.append("            Res {")
            out.append(f"                path: {raw(path)},")
            out.append(f"                text: {raw(res['text'])},")
            out.append(f"                status: {res.get('status', 200)},")
            out.append(f"                delay_ms: {res.get('delay_ms', 0)},")
            out.append(f"                content_type: {wrapped},")
            out.append(f"                headers: &[{headers}],")
            out.append("                options: Options::None,")
            out.append("            },")
        out.append("        ],")
        out.append("        queries: &[")
        for query, result in zip(case["measure"], results[case["name"]], strict=True):
            value = json.dumps(result["value"], separators=(",", ":"), ensure_ascii=False)
            out.append(f"            ({raw(query['js'])}, {raw(value)}),")
        out.append("        ],")
        out.append("    },")
    out.append("];")
    return "\n".join(out) + "\n"


def write_module_cases(chromium_json: Path) -> int:
    """Writes the cases file of the module script probe from the `probe
    --json` output in `chromium_json`."""
    root = paths.repo_root()
    probe = json.loads((root / PROBE_FILE).read_text(encoding="utf-8"))
    chromium = json.loads(chromium_json.read_text(encoding="utf-8"))
    (root / CASES_FILE).write_text(render(probe, chromium), encoding="utf-8")
    print(f"wrote {CASES_FILE}")
    return 0


def write_module_graph_cases(chromium_json: Path) -> int:
    """Writes the cases file of the module graph probe (without the cases of
    sub-feature 3b-2) from the `probe --json` output in `chromium_json`."""
    root = paths.repo_root()
    probe = json.loads((root / GRAPH_PROBE_FILE).read_text(encoding="utf-8"))
    chromium = json.loads(chromium_json.read_text(encoding="utf-8"))
    text = render(probe, chromium, GRAPH_PROBE_FILE, graph_later)
    (root / GRAPH_CASES_FILE).write_text(text, encoding="utf-8")
    print(f"wrote {GRAPH_CASES_FILE}")
    return 0
