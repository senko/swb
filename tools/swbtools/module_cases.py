"""Writes the Rust cases of the probe files that run in
`crates/engine/tests/probe_net.rs`, with Chromium's values:
`crates/engine/tests/probe_net/modules.rs` from
`tools/probes/web-module-scripts.json` (`module-cases`),
`crates/engine/tests/probe_net/module_graph.rs` from
`tools/probes/web-module-graph.json` (`module-graph-cases`) and
`crates/engine/tests/probe_net/custom_elements.rs` from
`tools/probes/web-custom-elements.json` (`ce-cases`; the cases with
JavaScript off are left out: they have no `js` queries) and
`crates/engine/tests/probe_net/shadow_dom.rs` from
`tools/probes/web-shadow-dom.json` (`shadow-cases`) and
`crates/engine/tests/probe_net/top_layer.rs` from
`tools/probes/web-top-layer.json` (`top-layer-cases`).

Run Chromium three times and check that the outputs are equal (docs/testing.md),
then pass one output:

    uv run --project tools swbtools probe --json \\
        tools/probes/web-module-scripts.json > chromium.json
    uv run --project tools swbtools module-cases chromium.json
    just fmt
"""

import json
from collections.abc import Callable
from pathlib import Path
from typing import Any

from swbtools import paths
from swbtools.rust_cases import raw

PROBE_FILE = Path("tools/probes/web-module-scripts.json")
CASES_FILE = Path("crates/engine/tests/probe_net/modules.rs")
GRAPH_PROBE_FILE = Path("tools/probes/web-module-graph.json")
GRAPH_CASES_FILE = Path("crates/engine/tests/probe_net/module_graph.rs")
CE_PROBE_FILE = Path("tools/probes/web-custom-elements.json")
CE_CASES_FILE = Path("crates/engine/tests/probe_net/custom_elements.rs")
SHADOW_PROBE_FILE = Path("tools/probes/web-shadow-dom.json")
SHADOW_CASES_FILE = Path("crates/engine/tests/probe_net/shadow_dom.rs")
TOP_LAYER_PROBE_FILE = Path("tools/probes/web-top-layer.json")
TOP_LAYER_CASES_FILE = Path("crates/engine/tests/probe_net/top_layer.rs")

# The command and the section of docs/testing.md of each probe file.
COMMANDS = {
    PROBE_FILE: ("module-cases", "Module script tests"),
    GRAPH_PROBE_FILE: ("module-graph-cases", "Module script tests"),
    CE_PROBE_FILE: ("ce-cases", "Custom element tests"),
    SHADOW_PROBE_FILE: ("shadow-cases", "Shadow DOM tests"),
    TOP_LAYER_PROBE_FILE: ("top-layer-cases", "Top layer tests"),
}

# The subcommand of each cases file: its probe file and its Rust file.
SUBCOMMANDS = {
    "module-cases": (PROBE_FILE, CASES_FILE),
    "module-graph-cases": (GRAPH_PROBE_FILE, GRAPH_CASES_FILE),
    "ce-cases": (CE_PROBE_FILE, CE_CASES_FILE),
    "shadow-cases": (SHADOW_PROBE_FILE, SHADOW_CASES_FILE),
    "top-layer-cases": (TOP_LAYER_PROBE_FILE, TOP_LAYER_CASES_FILE),
}


def render(
    probe: dict[str, Any],
    chromium: dict[str, Any],
    probe_file: Path = PROBE_FILE,
    skip: Callable[[str], bool] = lambda _: False,
) -> str:
    """Returns the Rust source of the cases: the probe file `probe` with the
    values in the `probe --json` output `chromium`, without the cases that
    `skip` names. Raises `KeyError` for a case that Chromium did not run."""
    results = {c["name"]: c["results"] for c in chromium["cases"]}
    command, section = COMMANDS[probe_file]
    out = [
        f"// The cases of {probe_file.as_posix()} with the values of Chromium 148.0.",
        f"// Generated by `swbtools {command}` from `swbtools probe --json` (three runs, all",
        f'// equal; then `just fmt`; see docs/testing.md, "{section}"); do not edit.',
        "",
        "use crate::{Case, Options, Res};"
        if any(case.get("resources") for case in probe["cases"])
        else "use crate::Case;",
        "",
        "pub(crate) const CASES: &[Case] = &[",
    ]
    for case in probe["cases"]:
        if skip(case["name"]) or not case.get("javascript", probe.get("javascript", False)):
            continue
        out.append("    Case {")
        out.append(f"        name: {raw(case['name'])},")
        out.append(f"        html: {raw(case['html'])},")
        out.append("        resources: &[")
        for path, res in case.get("resources", {}).items():
            content_type = res.get("content_type")
            wrapped = f"Some({raw(content_type)})" if content_type else "None"
            headers = ", ".join(f"({raw(k)}, {raw(v)})" for k, v in res.get("headers", {}).items())
            out.append("            Res {")
            out.append(f"                path: {raw(path)},")
            out.append(f"                text: {raw(res['text'])},")
            out.append(f"                status: {res.get('status', 200)},")
            out.append(f"                delay_ms: {res.get('delay_ms', 0)},")
            out.append(f"                content_type: {wrapped},")
            out.append(f"                headers: &[{headers}],")
            out.append("                options: Options::None,")
            out.append("            },")
        out.append("        ],")
        out.append("        queries: &[")
        for query, result in zip(case["measure"], results[case["name"]], strict=True):
            value = json.dumps(result["value"], separators=(",", ":"), ensure_ascii=False)
            out.append(f"            ({raw(query['js'])}, {raw(value)}),")
        out.append("        ],")
        out.append("    },")
    out.append("];")
    return "\n".join(out) + "\n"


def write_cases(probe_file: Path, cases_file: Path, chromium_json: Path) -> int:
    """Writes the cases file `cases_file` of the probe file `probe_file` from
    the `probe --json` output in `chromium_json`."""
    root = paths.repo_root()
    probe = json.loads((root / probe_file).read_text(encoding="utf-8"))
    chromium = json.loads(chromium_json.read_text(encoding="utf-8"))
    text = render(probe, chromium, probe_file)
    (root / cases_file).write_text(text, encoding="utf-8")
    print(f"wrote {cases_file}")
    return 0
