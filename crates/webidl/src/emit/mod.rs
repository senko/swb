//! The generator of the binding glue (ADR 0028 section 5): one Rust
//! module per interface, `types.rs` with the dictionaries, enumerations,
//! unions and callbacks, and `mod.rs` with the class numbers, the
//! registration of the classes and the creation of the interfaces in a
//! realm.
//!
//! The generated code calls the support code of `swb-web` (`bindings`),
//! named by a path that the set chooses (`crate::bindings` inside
//! `swb-web`, `swb_web::bindings` for the tests). It is formatted by hand
//! and marked `#[rustfmt::skip]` where it is included.

#![allow(
    clippy::too_many_lines,
    reason = "the emitters write code templates line by line; a split would tear them apart"
)]

mod iface;
mod items;
mod legacy;
pub(crate) mod names;
mod types;

use std::cell::RefCell;
use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::Error;
use crate::ast::Type;
use crate::model::{Iface, Model};

use names::{constant, literal, snake};

/// The generator of one set.
pub(crate) struct Gen<'a> {
    model: &'a Model,
    /// The path of the support module (`crate::bindings`).
    support: &'a str,
    /// The source files, for the headers.
    sources: &'a [String],
    /// The union types in use, by Rust name, with their flattened members.
    unions: RefCell<BTreeMap<String, Vec<Type>>>,
}

/// Generates the files of a set: `(file name, text)` pairs.
pub(crate) fn generate(
    model: &Model,
    support: &str,
    sources: &[String],
) -> Result<Vec<(String, String)>, Error> {
    let generator = Gen {
        model,
        support,
        sources,
        unions: RefCell::new(BTreeMap::new()),
    };
    if model.iface("DOMException").is_none() {
        return Err(Error {
            file: sources.first().cloned().unwrap_or_default(),
            line: 1,
            message:
                "a set of IDL files needs the interface DOMException (crates/web/idl/webidl.idl)"
                    .to_owned(),
        });
    }
    let mut files = Vec::new();
    for iface in &model.interfaces {
        files.push((
            format!("{}.rs", snake(&iface.name)),
            generator.iface_file(iface)?,
        ));
    }
    // After the interfaces: they register the unions that `types.rs` has.
    files.push(("types.rs".to_owned(), generator.types_file()?));
    files.push(("mod.rs".to_owned(), generator.mod_file()));
    files.sort();
    Ok(files)
}

impl Gen<'_> {
    /// The header of a generated file.
    fn header(&self, what: &str) -> String {
        format!(
            "// Generated by swb-webidl from {}. Do not edit: change the IDL files\n// and run `just bindings`.\n\n//! The binding glue of {what}.\n\n",
            self.sources.join(", ")
        )
    }

    /// The text of `mod.rs`.
    fn mod_file(&self) -> String {
        let mut out = format!(
            "// Generated by swb-webidl from {}. Do not edit: change the IDL files\n// and run `just bindings`.\n\n//! The generated binding glue (ADR 0028 section 5): one module per\n//! interface with the trait of its hand-written behaviour, `types` with\n//! the dictionaries, enumerations, unions and callbacks, the class\n//! numbers, [`define_classes`] and [`create_interfaces`].\n\n",
            self.sources.join(", ")
        );
        for iface in &self.model.interfaces {
            let _ = writeln!(out, "pub mod {};", snake(&iface.name));
        }
        out.push_str("pub mod types;\n\n");
        let _ = writeln!(out, "use {} as b;\n", self.support);
        for (i, iface) in self.model.interfaces.iter().enumerate() {
            let _ = writeln!(
                out,
                "/// The class of `{}`.\npub const {}: swb_js::ClassId = swb_js::ClassId::from_index({i});",
                iface.name,
                constant(&iface.name)
            );
        }
        let iterators = self.pair_iterables();
        for (i, iface) in iterators.iter().enumerate() {
            let _ = writeln!(
                out,
                "/// The class of the default iterator objects of `{}` (Web IDL §3.7.9.1).\npub const {}: swb_js::ClassId = swb_js::ClassId::from_index({});",
                iface.name,
                legacy::iterator_constant(&iface.name),
                self.model.interfaces.len() + i
            );
        }
        let traits: Vec<String> = self
            .model
            .interfaces
            .iter()
            .map(|i| format!("{}::{}Impl", snake(&i.name), i.name))
            .collect();
        let _ = writeln!(
            out,
            "\n/// The hand-written behaviour of all interfaces of the set.\npub trait Bindings: b::Host + {} {{}}\n\nimpl<T: b::Host + {}> Bindings for T {{}}\n",
            traits.join(" + "),
            traits.join(" + ")
        );
        out.push_str("/// Registers the classes of the set in a new runtime, before any other\n/// class (the glue names them by number).\n#[allow(clippy::too_many_lines)]\npub fn define_classes<H: Bindings>(rt: &mut swb_js::Runtime) -> swb_js::VmResult<()> {\n");
        for iface in &self.model.interfaces {
            let mut spec = format!("swb_js::ClassSpec::new({})", literal(&iface.name));
            if let Some(parent) = &iface.parent {
                let _ = write!(spec, ".parent({})", constant(parent));
            }
            if let Some(length) = constructor_length(iface) {
                let _ = write!(
                    spec,
                    ".constructor({}::construct::<H>, {length})",
                    snake(&iface.name)
                );
            }
            if self.model.legacy(iface).is_legacy() {
                let _ = write!(spec, ".hooks({}::hooks::<H>())", snake(&iface.name));
            }
            let _ = writeln!(
                out,
                "    b::glue::define_class(rt, {spec}, {})?;",
                constant(&iface.name)
            );
        }
        for iface in &iterators {
            let _ = writeln!(
                out,
                "    b::glue::define_class(rt, swb_js::ClassSpec::new({}), {})?;",
                literal(&format!("{} Iterator", iface.name)),
                legacy::iterator_constant(&iface.name)
            );
        }
        out.push_str("    Ok(())\n}\n\n");
        out.push_str("/// Creates the interfaces of the set in `realm` and defines the exposed\n/// ones on the global object.\n#[allow(clippy::too_many_lines)]\npub fn create_interfaces<H: Bindings>(rt: &mut swb_js::Runtime, realm: u32) -> swb_js::VmResult<()> {\n");
        for iface in &self.model.interfaces {
            let module = snake(&iface.name);
            if crate::model::exposed_in_window(&iface.ext_attrs) {
                let _ = writeln!(
                    out,
                    "    let interface = {module}::define::<H>(rt, realm)?;\n    b::glue::expose(rt, realm, {}, interface)?;",
                    literal(&iface.name)
                );
            } else {
                let _ = writeln!(out, "    {module}::define::<H>(rt, realm)?;");
            }
        }
        let global = self
            .model
            .interfaces
            .iter()
            .find(|i| i.ext_attrs.has("Global"));
        if let Some(global) = global {
            let chain: Vec<String> = self
                .model
                .chain(global)
                .iter()
                .map(|i| constant(&i.name))
                .collect();
            let _ = writeln!(
                out,
                "    // Web IDL §3.7.3: the prototypes of a [Global] interface and of its\n    // ancestors are immutable prototype objects.\n    b::glue::immutable_prototypes(rt, realm, &[{}])?;",
                chain.join(", ")
            );
        }
        out.push_str("    Ok(())\n}\n");
        if let Some(global) = global {
            let _ = write!(
                out,
                "\n/// Makes the global object of `realm` an instance of `{0}` with `data`\n/// (after [`create_interfaces`]); it is an immutable prototype object\n/// (Web IDL §3.8.1).\npub fn init_global<H: Bindings>(rt: &mut swb_js::Runtime, realm: u32, data: swb_js::HostData) -> swb_js::VmResult<()> {{\n    rt.init_global(realm, {1}, data)?;\n    let global = rt.global(realm)?;\n    rt.set_immutable_prototype(global)\n}}\n",
                global.name,
                constant(&global.name)
            );
        }
        out
    }

    /// The interfaces with a pair iterator, in class order (their
    /// iterator classes follow the interface classes).
    fn pair_iterables(&self) -> Vec<&Iface> {
        self.model
            .interfaces
            .iter()
            .filter(|i| crate::legacy::iterable(i).is_some_and(|it| it.key.is_some()))
            .collect()
    }
}

/// The `length` of the interface object: the shortest required argument
/// count of the constructors.
fn constructor_length(iface: &Iface) -> Option<usize> {
    iface
        .members
        .iter()
        .filter_map(|m| match m {
            crate::ast::Member::Constructor(op) => Some(
                op.args
                    .iter()
                    .take_while(|a| !a.optional && !a.variadic)
                    .count(),
            ),
            _ => None,
        })
        .min()
}
