//! The names of the event handler IDL attributes (HTML §8.1.8.1,
//! <https://html.spec.whatwg.org/multipage/webappapis.html#event-handlers-on-elements,-document-objects,-and-window-objects>)
//! with the event type of each. The list is that of the mixins
//! `GlobalEventHandlers`, `DocumentAndElementEventHandlers` and
//! `WindowEventHandlers` and of the extra `Document` handlers in
//! `crates/web/idl/html.idl` and `pointer-events.idl`; a unit test of
//! `handlers.rs` compares it with the IDL.

use super::handlers::{Class, Name};

/// An attribute `on` + the event type.
macro_rules! h {
    ($class:ident, $event:literal) => {
        Name {
            attr: concat!("on", $event),
            event: $event,
            class: Class::$class,
        }
    };
}

